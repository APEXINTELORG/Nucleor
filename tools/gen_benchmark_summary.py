#!/usr/bin/env python3
"""
Read tools/verify_timings.csv and emit docs/BENCHMARK.md — a per-release
verify-gate performance + parity dashboard.

Implements RFC-0028-EXTERNAL_ROADMAP_INPUT_2026-04-28.md Pick B: a public
benchmark dashboard that separates parity / performance / claim. The
local CSV is gitignored (per-machine timing data); this script
distills it into a publishable per-run summary.

Output table columns:
  run_iso (UTC) · pass · fail · total_steps · total_seconds · slowest_step

Also emits:
  - Top-3 slowest steps in the most recent run (for performance triage)
  - Total-time delta vs the previous run (regression hint)

Run it after a verify pass to refresh BENCHMARK.md before commit.

Usage:
  python tools/gen_benchmark_summary.py
  python tools/gen_benchmark_summary.py --csv path/to/other.csv --out path/to/other.md
"""
import argparse
import csv
import os
from collections import defaultdict


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", default="tools/verify_timings.csv",
                    help="path to per-step timing CSV (default: %(default)s)")
    ap.add_argument("--out", default="docs/BENCHMARK.md",
                    help="output markdown path (default: %(default)s)")
    args = ap.parse_args()

    if not os.path.isfile(args.csv):
        print(f"error: {args.csv} not found")
        print(f"hint: run `bash tools/verify.sh` to populate it")
        return 1

    runs = defaultdict(lambda: {"pass": 0, "fail": 0, "skip": 0,
                                "total_secs": 0.0, "slowest": ("", 0.0),
                                "step_count": 0, "steps": []})

    with open(args.csv, newline="", encoding="utf-8") as f:
        reader = csv.reader(f)
        header = next(reader, None)
        for row in reader:
            if len(row) < 5:
                continue
            run_iso, _idx, secs_s, status, name = row[0], row[1], row[2], row[3], row[4]
            try:
                secs = float(secs_s)
            except ValueError:
                continue
            r = runs[run_iso]
            if status == "PASS":
                r["pass"] += 1
                r["total_secs"] += secs
                r["step_count"] += 1
                r["steps"].append((secs, name))
                if secs > r["slowest"][1]:
                    r["slowest"] = (name, secs)
            elif status == "FAIL":
                r["fail"] += 1
                r["total_secs"] += secs
                r["step_count"] += 1
                r["steps"].append((secs, name))
            elif status == "SKIP":
                r["skip"] += 1

    if not runs:
        print(f"error: no runs found in {args.csv}")
        return 1

    sorted_runs = sorted(runs.keys())
    latest = sorted_runs[-1]
    prev = sorted_runs[-2] if len(sorted_runs) >= 2 else None

    lines = []
    lines.append("# Verify-Gate Benchmark Summary")
    lines.append("")
    lines.append(f"**Source:** `{args.csv}` ({len(sorted_runs)} runs recorded)")
    lines.append("")
    lines.append("Per-release verify-gate performance and parity. Generated by")
    lines.append("`tools/gen_benchmark_summary.py` from local timing CSV. The CSV")
    lines.append("itself is gitignored (per-machine output); this distillation")
    lines.append("is the publishable per-release record.")
    lines.append("")
    lines.append("## Latest run")
    lines.append("")
    r = runs[latest]
    lines.append(f"- **Run:** `{latest}`")
    lines.append(f"- **Result:** {r['pass']} PASS · {r['fail']} FAIL · {r['skip']} SKIP")
    lines.append(f"- **Total wall time:** {r['total_secs']:.2f}s across {r['step_count']} timed steps")
    lines.append(f"- **Slowest step:** `{r['slowest'][0]}` ({r['slowest'][1]:.2f}s)")
    if prev:
        delta = r["total_secs"] - runs[prev]["total_secs"]
        sign = "+" if delta >= 0 else ""
        pct = 100.0 * delta / runs[prev]["total_secs"] if runs[prev]["total_secs"] else 0.0
        lines.append(f"- **vs previous run** (`{prev}`): {sign}{delta:.2f}s "
                     f"({sign}{pct:.1f}%)")
    lines.append("")
    lines.append("## Top 5 slowest steps in latest run")
    lines.append("")
    lines.append("| Time | Step |")
    lines.append("|---|---|")
    top5 = sorted(r["steps"], reverse=True)[:5]
    for secs, name in top5:
        lines.append(f"| {secs:.2f}s | `{name}` |")
    lines.append("")
    lines.append("## All recorded runs (chronological)")
    lines.append("")
    lines.append("| Run (UTC) | Pass | Fail | Steps | Total | Slowest |")
    lines.append("|---|---|---|---|---|---|")
    for ts in sorted_runs:
        r = runs[ts]
        slowest_name = r["slowest"][0]
        if len(slowest_name) > 40:
            slowest_name = slowest_name[:37] + "..."
        lines.append(f"| `{ts}` | {r['pass']} | {r['fail']} | {r['step_count']} "
                     f"| {r['total_secs']:.2f}s | `{slowest_name}` |")
    lines.append("")
    lines.append("## Notes")
    lines.append("")
    lines.append("- **Parity:** PASS / FAIL counts. v0.4.x baseline is 467/467 at v0.4.41.")
    lines.append("- **Performance:** total wall time. v0.4.28 baseline was ~314s; v0.4.39")
    lines.append("  + v0.4.30 optimizations brought the floor to ~295s.")
    lines.append("- **Claim separation:** this dashboard does NOT claim absolute")
    lines.append("  performance comparisons against other languages — those require")
    lines.append("  controlled hardware + the public benchmark program (RFC-TBD).")
    lines.append("  This is the verify-gate cycle time on the local developer box.")
    lines.append("")

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print(f"Wrote {args.out}")
    print(f"  Runs: {len(sorted_runs)} · Latest: {latest} "
          f"· {runs[latest]['total_secs']:.2f}s / "
          f"{runs[latest]['pass']} pass / {runs[latest]['fail']} fail")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
